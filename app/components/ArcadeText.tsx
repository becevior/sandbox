type ArcadeTextProps = {
  text: string;
  className?: string;
  // When set, the lettering scales to the CSS height and keeps its proportions.
  fluid?: boolean;
};

export default function ArcadeText({ text, className, fluid = false }: ArcadeTextProps) {
  let offset = 0;
  const letters = Array.from(text.toUpperCase(), (letter, index) => {
    if (letter === " ") {
      offset += 4;
      return null;
    }
    const glyph = arcadeGlyphs[letter] ?? arcadeGlyphs["?"];
    const x = offset;
    offset += glyph[0].length + 1.5;
    return (
      <g key={index} transform={`translate(${x} 0)`}>
        {glyph.flatMap((row, y) => Array.from(row, (pixel, column) =>
          pixel === "1" ? <rect key={`${y}-${column}`} x={column} y={y} width="1" height="1" /> : null
        ))}
      </g>
    );
  });
  const width = (offset + 2) * 2;
  const style: CSSProperties | undefined = fluid ? { width: "auto", aspectRatio: `${width} / 27` } : undefined;
  return (
    <svg
      className={className}
      width={width}
      height="27"
      viewBox={`-1 -1 ${offset + 2} 9`}
      preserveAspectRatio="none"
      aria-hidden="true"
      style={style}
    >
      {letters}
    </svg>
  );
}
